public class SwapOfNum{
	public static void main(String[] args){
		
		int num1 =10;
		int num2 = 19;
		System.out.println("Before swaping of two numbers :  num1 = "+num1+ ", num2 = "+num2);

		int temp =num1;
		num1 = num2;
		num2 = temp;
		System.out.println("After swaping of two numbers :  num1 = "+num1+ ", num2 = "+num2);

}

}